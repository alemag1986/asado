// Regenerates app/src/lib/region.ts — the southern-cone coastlines drawn as
// an equirectangular SVG path, projected with a cos(35°S) latitude scale so
// the patch does not stretch itself into a thin vertical sliver.
//
// Source: Natural Earth 110m admin-0 coastlines (public domain), republished
// by https://github.com/johan/world.geo.json (ISO2 files).
//
//   node scripts/gen-region.mjs  — headless downloads + rewrites region.ts

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const SRC = 'https://raw.githubusercontent.com/johan/world.geo.json/master/countries';
const COUNTRIES = [
  { iso: 'ARG', name: 'argentina' },
  { iso: 'URY', name: 'uruguay' },
  { iso: 'BRA', name: 'brazil' },
  { iso: 'CHL', name: 'chile' },
  { iso: 'BOL', name: 'bolivia' },
  { iso: 'PRY', name: 'paraguay' },
];
const CACHE = '/tmp/region-data';
const OUT = new URL('../app/src/lib/region.ts', import.meta.url);

const LAT_SCALE = Math.cos((35 * Math.PI) / 180); // standard parallel 35°S

const MARKERS = [
  { id: 'norte', lat: -24.782, lon: -65.423, color: 'var(--flame)' },
  { id: 'cordoba', lat: -31.42, lon: -64.188, color: 'var(--ember)' },
  { id: 'buenosaires', lat: -34.603, lon: -58.382, color: 'var(--carne)' },
  { id: 'uruguay', lat: -34.905, lon: -56.191, color: 'var(--yolk)' },
  { id: 'patagonia', lat: -42.771, lon: -65.036, color: 'var(--coal)' },
];

const MARGIN_LON = 2.0;
const MARGIN_LAT = 1.6;
const MIN_RING_AREA = 0.04; // map-units² — drops scrub islands
const ROUND = 100; // 2 decimals

const x = (lon) => (+lon).toFixed(2);
const y = (lat) => {
  const v = Math.round(-lat * LAT_SCALE * ROUND) / ROUND;
  return v === -0 ? '0' : `${v}`;
};

function ringArea(ring) {
  let sum = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, lat1] = ring[i];
    const [x2, lat2] = ring[(i + 1) % ring.length];
    sum += x1 * -lat2 * LAT_SCALE - -lat1 * LAT_SCALE * x2;
  }
  return Math.abs(sum / 2);
}

function ringToPath(ring) {
  let d = '';
  for (const [i, [lon, lat]] of ring.entries()) {
    d += `${i === 0 ? 'M' : 'L'}${x(lon)} ${y(lat)}`;
  }
  return `${d}Z`;
}

function geometryToPath(geom) {
  const polygons = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  const rings = polygons
    .flatMap((poly) => poly.map((ring) => ({ ring, area: ringArea(ring) })))
    .filter(({ area }) => area >= MIN_RING_AREA)
    .map(({ ring }) => ring);
  return rings
    .sort((a, b) => ringArea(b) - ringArea(a))
    .map(ringToPath)
    .join('');
}

async function download() {
  await mkdir(CACHE, { recursive: true });
  for (const { iso } of COUNTRIES) {
    const file = path.join(CACHE, `${iso}.geo.json`);
    if (existsSync(file)) continue;
    const res = await fetch(`${SRC}/${iso}.geo.json`);
    if (!res.ok) throw new Error(`download ${iso} failed: ${res.status}`);
    await writeFile(file, await res.text());
    console.log('fetched', iso);
  }
}

async function main() {
  await download();
  const land = {};
  for (const { iso, name } of COUNTRIES) {
    const fc = JSON.parse(await readFile(path.join(CACHE, `${iso}.geo.json`), 'utf8'));
    land[name] = geometryToPath(fc.features[0].geometry);
  }

  const lons = MARKERS.map((m) => m.lon);
  const lats = MARKERS.map((m) => m.lat);
  const minLon = Math.min(...lons) - MARGIN_LON;
  const maxLon = Math.max(...lons) + MARGIN_LON;
  const minLat = Math.min(...lats) - MARGIN_LAT;
  const maxLat = Math.max(...lats) + MARGIN_LAT;

  const src = `// Generated by scripts/gen-region.mjs — do not edit by hand.
// Natural Earth 110m admin-0 coastlines (public domain) projected as equirect
// with a cos(35°S) latitude scale: east = +x, north = -y. Markers are pinned
// at true lat/lon; {@link regionProject} maps degrees into viewBox units.

export const REGION_SRC = 'southern cone · Natural Earth 110m (public domain)';

/** Latitude scale factor — bakes the equirect "standard parallel" in. */
export const REGION_LAT_SCALE = ${LAT_SCALE};

/** Degree window the map is cropped to (padding already added). */
export const REGION_WINDOW = {
  minLon: ${minLon},
  maxLon: ${maxLon},
  minLat: ${minLat},
  maxLat: ${maxLat},
} as const;

export interface RegionMarker {
  id: string;
  lat: number;
  lon: number;
  /** CSS token or hex, e.g. 'var(--ember)'. */
  color: string;
}

/** Projects degrees into map units (viewBox space). */
export function regionProject(lat: number, lon: number): { x: number; y: number } {
  return { x: lon, y: -lat * REGION_LAT_SCALE };
}

/** Coastlines per country, already projected to viewBox units. */
export const REGION_LAND: Record<string, string> = {
${COUNTRIES.map(({ name }) => `  ${name}: '${land[name]}',`).join('\n')}
};

export const REGION_MARKERS: RegionMarker[] = [
${MARKERS.map((m) => `  { id: '${m.id}', lat: ${m.lat}, lon: ${m.lon}, color: '${m.color}' },`).join('\n')}
];
`;

  const kb = (src.length / 1024).toFixed(1);
  await writeFile(OUT, src);
  const w = maxLon - minLon;
  const h = (maxLat - minLat) * LAT_SCALE;
  console.log(`wrote ${OUT.href} (${kb}KB), window ${w}x${h.toFixed(2)} map units (aspect ${(w / h).toFixed(2)})`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});